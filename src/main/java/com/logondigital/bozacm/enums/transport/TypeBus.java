package com.logondigital.bozacm.enums.transport;

/**
 * Énumération des types de bus disponibles.
 * Utilisé pour différencier les catégories de bus lors d'une réservation.
 */
public enum TypeBus {

    /**
     * Bus standard - Sièges classiques, confort basique
     */
    STANDARD,

    /**
     * Bus VIP - Sièges confortables, climatisation, espace jambes
     */
    VIP,

}