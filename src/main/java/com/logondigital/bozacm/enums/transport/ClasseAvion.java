package com.logondigital.bozacm.enums.transport;

/**
 * Énumération des classes d'avion disponibles.
 * Utilisé pour différencier les catégories de sièges dans les avions.
 */
public enum ClasseAvion {

    /**
     * Classe économique - Tarif standard, sièges basiques
     */
    ECONOMIE,

    /**
     * Classe affaires - Confort supérieur, repas améliorés, sièges inclinables
     */
    AFFAIRES,

    /**
     * Première classe - Luxe maximal, service premium, sièges-lits
     */
    PREMIERE
}